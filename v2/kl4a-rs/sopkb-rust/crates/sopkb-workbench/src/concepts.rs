/// docs/port/port-mapping-e-web-cli-contract.md §4.4: `get_concept_index() -> [Concept
/// { id, label, item_count, rule_count, statuses: map<ReviewStatus,int> }]`.
#[derive(Debug, Clone, PartialEq)]
pub struct ConceptSummary {
    pub id: String,
    pub label: String,
    pub item_count: usize,
    pub rule_count: usize,
    /// Only statuses that actually occur are present -- Python's `concept_index`
    /// builds this as a plain `dict` that starts empty and only gains a key when an
    /// item with that `review_status` is seen (`web_app.py:900-902`); it is NOT
    /// zero-filled for the other four `ReviewStatus` values. Confirmed against real
    /// Python output (every concept in the reference fixture carries only
    /// `{"proposed": N}`, never `{"proposed": N, "approved": 0, ...}`).
    pub statuses: BTreeMap<String, i64>,
}

/// Internal, full-fidelity grouping (Python's actual `concept_index` dict entry,
/// `items` included) -- [`concept_index`] projects this down to [`ConceptSummary`];
/// [`get_concept_detail`] and [`focused_graph_for_concept`] need the full items list,
/// which the wire-shaped summary deliberately drops (per
/// docs/port/port-mapping-e-web-cli-contract.md §4.4's `get_concept_index` signature).
struct ConceptGroup {
    id: String,
    label: String,
    items: Vec<Value>,
    rule_count: usize,
    statuses: BTreeMap<String, i64>,
}

/// `concept_index`'s core loop (`web_app.py:882-903`), minus the final summary
/// projection: groups `knowledge_items` by `concept_for_label(item.subject)`, in
/// first-appearance order (mirroring Python `dict.setdefault`'s insertion order,
/// which the final `sorted(..., key=...)`'s STABLE sort relies on for its tiebreak).
fn concept_groups(bundle_dir: &Path) -> Result<Vec<ConceptGroup>> {
    let mut groups: Vec<ConceptGroup> = Vec::new();
    let mut index: HashMap<String, usize> = HashMap::new();

    for item in knowledge_items(bundle_dir)? {
        let subject = item["subject"].as_str().unwrap_or("");
        let concept = concept_for_label(subject);
        let idx = *index.entry(concept.id.clone()).or_insert_with(|| {
            groups.push(ConceptGroup { id: concept.id.clone(), label: concept.label.clone(), items: Vec::new(), rule_count: 0, statuses: BTreeMap::new() });
            groups.len() - 1
        });
        let group = &mut groups[idx];
        // rule_count SUMS decision_rules_for_item across every item in the concept --
        // NOT deduplicated (`entry["rule_count"] = int(entry["rule_count"]) + len(decision_rules_for_item(item))`,
        // web_app.py:897-899). Confirmed against real Python output.
        group.rule_count += decision_rules_for_item(&item).len();
        let status = item["review_status"].as_str().unwrap_or("").to_string();
        *group.statuses.entry(status).or_insert(0) += 1;
        group.items.push(item);
    }
    Ok(groups)
}

fn summarize(group: &ConceptGroup) -> ConceptSummary {
    ConceptSummary { id: group.id.clone(), label: group.label.clone(), item_count: group.items.len(), rule_count: group.rule_count, statuses: group.statuses.clone() }
}

/// `concept_index` (`web_app.py:882-903`). Sort: `label.lower()` ascending, via a
/// STABLE sort (`Vec::sort_by_key` is stable, matching Python's `sorted()`), so two
/// concepts whose labels are identical after lowercasing keep their original
/// first-appearance order -- the only sensible tiebreak reading of Python's own
/// Timsort-stability-dependent behavior, since `web_app.py` never states a tiebreak
/// rule explicitly.
pub fn concept_index(bundle_dir: &Path) -> Result<Vec<ConceptSummary>> {
    let groups = concept_groups(bundle_dir)?;
    let mut summaries: Vec<ConceptSummary> = groups.iter().map(summarize).collect();
    summaries.sort_by_key(|c| c.label.to_lowercase());
    Ok(summaries)
}

/// docs/port/port-mapping-e-web-cli-contract.md §4.4: `get_concept_detail(concept_id)
/// -> { concept, items: [KnowledgeItem], rules: [DecisionRule] }` -- "drop the
/// server-side `[:24]` cap, page in React" (Python's `render_concept_detail` caps
/// `rules[:24]` for HTML rendering only; this is a data-only read, uncapped).
#[derive(Debug)]
pub struct ConceptDetail {
    pub concept: ConceptSummary,
    pub items: Vec<Value>,
    pub rules: Vec<Value>,
}

/// P-W24 FIX: an unknown `concept_id` is a `NotFound` error here, not Python's
/// `render_concepts`/`render_graph` silent fallback-to-first-entry (`web_app.py:910-913`,
/// `:1238-1241`) -- this library layer never guesses on behalf of a caller; a future UI
/// can choose to fall back to `concept_index(...)[0]` itself if it wants that UX.
pub fn get_concept_detail(bundle_dir: &Path, concept_id: &str) -> Result<ConceptDetail> {
    let groups = concept_groups(bundle_dir)?;
    let group = groups.into_iter().find(|g| g.id == concept_id).ok_or_else(|| SopkbError::NotFound(format!("unknown concept: {concept_id}")))?;
    let rules: Vec<Value> = group.items.iter().flat_map(decision_rules_for_item).collect();
    let concept = summarize(&group);
    Ok(ConceptDetail { concept, items: group.items, rules })
}

/// One node in a [`Graph`]. `node_type` matches Python's raw `type` string vocabulary
/// verbatim (`concept`, `knowledge_item`, `relation`, `rule`, `evidence`, plus
/// `source`/`section`/`review` used elsewhere in `graph_svg`'s palette but never
/// produced by `focused_graph_for_concept` itself).
#[derive(Debug, Clone, PartialEq)]
pub struct GraphNode {
    pub id: String,
    pub node_type: String,
    pub label: String,
}

#[derive(Debug, Clone, PartialEq)]
pub struct GraphEdge {
    pub source: String,
    pub target: String,
    pub edge_type: String,
}

#[derive(Debug, Clone, Default, PartialEq)]
pub struct Graph {
    pub nodes: Vec<GraphNode>,
    pub edges: Vec<GraphEdge>,
}

/// `default_graph_concept` (`web_app.py:1281-1295`): `max(concepts, key=(item_count,
/// rule_count, label))`. Python's `max()` returns the FIRST maximal element among
/// ties -- the OPPOSITE of Rust's `Iterator::max_by_key`/`max_by`, which returns the
/// LAST. Implemented manually with a strict `>` replace so ties resolve the same way
/// Python's does (first-seen wins). `concepts` is expected to already be
/// `concept_index`'s sorted (by `label.lower()`) output, matching
/// `render_graph`'s own `default_graph_concept(concept_index(bundle_dir))` call.
pub fn default_graph_concept(concepts: &[ConceptSummary]) -> Option<&ConceptSummary> {
    let mut best: Option<&ConceptSummary> = None;
    for c in concepts {
        let candidate_key = (c.item_count, c.rule_count, c.label.clone());
        let replace = match best {
            None => true,
            Some(b) => candidate_key > (b.item_count, b.rule_count, b.label.clone()),
        };
        if replace {
            best = Some(c);
        }
    }
    best
}

/// `focused_graph_for_concept` (`web_app.py:1298-1327`), re-derived directly from the
/// real Python source per docs/port/DECISIONS.md Q7 ("keeps its exact current
/// traversal, caps, and node/edge vocabulary"). Caps: 18 items per concept, 4 rules
/// per item -- PRESERVED bit-identically, including their divergence from `graph.json`'s
/// export vocabulary (F3), which Q7 explicitly keeps un-consolidated.
pub fn focused_graph_for_concept(bundle_dir: &Path, concept_id: &str) -> Result<Graph> {
    let groups = concept_groups(bundle_dir)?;
    let group = groups.into_iter().find(|g| g.id == concept_id).ok_or_else(|| SopkbError::NotFound(format!("unknown concept: {concept_id}")))?; // P-W24
    Ok(focused_graph_for_group(&group))
}

fn focused_graph_for_group(group: &ConceptGroup) -> Graph {
    let mut nodes = vec![GraphNode { id: group.id.clone(), node_type: "concept".to_string(), label: group.label.clone() }];
    let mut edges = Vec::new();

    for item in group.items.iter().take(18) {
        let item_id = item["id"].as_str().unwrap_or("").to_string();
        let relation_id = relation_id_for_item(item);
        let evidence_id = evidence_id_for_item(item);

        nodes.push(GraphNode { id: item_id.clone(), node_type: "knowledge_item".to_string(), label: item["object"].as_str().unwrap_or("").to_string() });
        nodes.push(GraphNode { id: relation_id.clone(), node_type: "relation".to_string(), label: item["predicate"].as_str().unwrap_or("").to_string() });
        nodes.push(GraphNode { id: evidence_id.clone(), node_type: "evidence".to_string(), label: item["source_text"].as_str().unwrap_or("").to_string() });

        edges.push(GraphEdge { source: group.id.clone(), target: item_id.clone(), edge_type: "anchors".to_string() });
        edges.push(GraphEdge { source: item_id.clone(), target: relation_id, edge_type: "has_relation".to_string() });
        edges.push(GraphEdge { source: item_id.clone(), target: evidence_id, edge_type: "supported_by".to_string() });

        for rule in decision_rules_for_item(item).into_iter().take(4) {
            let rule_id = rule["id"].as_str().unwrap_or("").to_string();
            nodes.push(GraphNode { id: rule_id.clone(), node_type: "rule".to_string(), label: rule["title"].as_str().unwrap_or("").to_string() });
            edges.push(GraphEdge { source: item_id.clone(), target: rule_id, edge_type: "has_rule".to_string() });
        }
    }

    Graph { nodes, edges }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    fn bundle_with_items(items: Value) -> (tempfile::TempDir, std::path::PathBuf) {
        let dir = tempdir().unwrap();
        let bundle_dir = dir.path().join("bundle");
        sopkb_core::store::create_bundle(&bundle_dir, Some("B")).unwrap();
        sopkb_core::store::write_state_json(&bundle_dir, "items.json", &items).unwrap();
        (dir, bundle_dir)
    }

    fn item(id: &str, subject: &str, status: &str) -> Value {
        serde_json::json!({
            "id": id, "subject": subject, "predicate": "requires", "object": "obj",
            "review_status": status, "source_id": "s1", "section_id": "sec1",
            "source_text": "text", "span_status": "exact", "start_pos": 0, "end_pos": 4,
        })
    }

    #[test]
    fn concept_index_sums_rule_count_and_omits_zero_statuses() {
        let items = serde_json::json!([
            item("ki-1", "Alpha", "proposed"),
            item("ki-2", "Alpha", "approved"),
        ]);
        let (_dir, bundle_dir) = bundle_with_items(items);
        let concepts = concept_index(&bundle_dir).unwrap();
        assert_eq!(concepts.len(), 1);
        let alpha = &concepts[0];
        assert_eq!(alpha.item_count, 2);
        // Each item with predicate "requires" and object present yields exactly one
        // decision rule from decision_rules_for_item -- rule_count sums, not dedupes.
        assert_eq!(alpha.rule_count, 2);
        assert_eq!(alpha.statuses.get("proposed"), Some(&1));
        assert_eq!(alpha.statuses.get("approved"), Some(&1));
        assert!(!alpha.statuses.contains_key("rejected"), "statuses must NOT be zero-filled");
        assert!(!alpha.statuses.contains_key("deferred"));
        assert!(!alpha.statuses.contains_key("edited"));
    }

    #[test]
    fn concept_index_sorts_case_insensitively_by_label() {
        let items = serde_json::json!([
            item("ki-1", "banana", "proposed"),
            item("ki-2", "Apple", "proposed"),
            item("ki-3", "Cherry", "proposed"),
        ]);
        let (_dir, bundle_dir) = bundle_with_items(items);
        let concepts = concept_index(&bundle_dir).unwrap();
        let labels: Vec<&str> = concepts.iter().map(|c| c.label.as_str()).collect();
        assert_eq!(labels, vec!["Apple", "banana", "Cherry"]);
    }

    /// Two items whose subjects differ only by case (e.g. "Apple" / "apple") always
    /// collapse into the SAME concept, because `concept_for_label`'s id is
    /// `concept-{slugify(label)}` and `slugify` itself lowercases first -- so
    /// `concept_index` can never actually produce two DISTINCT entries whose labels tie
    /// case-insensitively; the grouping key already merges them upstream of the sort.
    /// The first-seen item's label wins (Python's `dict.setdefault` semantics: only the
    /// FIRST occurrence's `concept["label"]` is stored).
    #[test]
    fn same_case_insensitive_subject_merges_into_one_concept_first_label_wins() {
        let items = serde_json::json!([
            item("ki-1", "Apple", "proposed"),
            item("ki-2", "apple", "approved"),
        ]);
        let (_dir, bundle_dir) = bundle_with_items(items);
        let concepts = concept_index(&bundle_dir).unwrap();
        assert_eq!(concepts.len(), 1);
        assert_eq!(concepts[0].label, "Apple", "first-seen label wins");
        assert_eq!(concepts[0].item_count, 2);
        assert_eq!(concepts[0].statuses.get("proposed"), Some(&1));
        assert_eq!(concepts[0].statuses.get("approved"), Some(&1));
    }

    #[test]
    fn get_concept_detail_unknown_id_is_not_found_p_w24() {
        let (_dir, bundle_dir) = bundle_with_items(serde_json::json!([item("ki-1", "Alpha", "proposed")]));
        let err = get_concept_detail(&bundle_dir, "concept-does-not-exist").unwrap_err();
        assert!(err.to_string().contains("unknown concept"));
    }

    #[test]
    fn get_concept_detail_returns_uncapped_rules() {
        let mut items_vec = Vec::new();
        for i in 0..30 {
            items_vec.push(item(&format!("ki-{i}"), "Alpha", "proposed"));
        }
        let (_dir, bundle_dir) = bundle_with_items(Value::Array(items_vec));
        let concepts = concept_index(&bundle_dir).unwrap();
        let detail = get_concept_detail(&bundle_dir, &concepts[0].id).unwrap();
        assert_eq!(detail.items.len(), 30);
        assert_eq!(detail.rules.len(), 30, "get_concept_detail must NOT apply the render-only [:24] cap");
    }

    #[test]
    fn focused_graph_for_concept_caps_18_items_and_4_rules_per_item() {
        let mut items_vec = Vec::new();
        for i in 0..25 {
            items_vec.push(item(&format!("ki-{i:02}"), "Alpha", "proposed"));
        }
        let (_dir, bundle_dir) = bundle_with_items(Value::Array(items_vec));
        let concepts = concept_index(&bundle_dir).unwrap();
        let graph = focused_graph_for_concept(&bundle_dir, &concepts[0].id).unwrap();
        // 1 concept node + 18 items * 3 nodes each (knowledge_item/relation/evidence) + up to 1 rule node each = 18*4 max
        let knowledge_item_nodes = graph.nodes.iter().filter(|n| n.node_type == "knowledge_item").count();
        assert_eq!(knowledge_item_nodes, 18, "must cap at 18 items per concept");
    }

    #[test]
    fn focused_graph_for_concept_unknown_id_is_not_found_p_w24() {
        let (_dir, bundle_dir) = bundle_with_items(serde_json::json!([item("ki-1", "Alpha", "proposed")]));
        let err = focused_graph_for_concept(&bundle_dir, "concept-nope").unwrap_err();
        assert!(err.to_string().contains("unknown concept"));
    }

    #[test]
    fn default_graph_concept_picks_first_among_ties_matching_python_max() {
        let concepts = vec![
            ConceptSummary { id: "c1".into(), label: "Alpha".into(), item_count: 3, rule_count: 1, statuses: BTreeMap::new() },
            ConceptSummary { id: "c2".into(), label: "Alpha".into(), item_count: 3, rule_count: 1, statuses: BTreeMap::new() },
        ];
        let winner = default_graph_concept(&concepts).unwrap();
        assert_eq!(winner.id, "c1", "Python's max() keeps the FIRST maximal element on a tie");
    }

    #[test]
    fn default_graph_concept_prefers_higher_item_count_then_rule_count_then_label() {
        let concepts = vec![
            ConceptSummary { id: "low".into(), label: "Zeta".into(), item_count: 1, rule_count: 9, statuses: BTreeMap::new() },
            ConceptSummary { id: "high".into(), label: "Alpha".into(), item_count: 5, rule_count: 0, statuses: BTreeMap::new() },
        ];
        assert_eq!(default_graph_concept(&concepts).unwrap().id, "high");
    }

    #[test]
    fn default_graph_concept_empty_is_none() {
        assert!(default_graph_concept(&[]).is_none());
    }
}
